// Sign-up seed: events.json weekly rows that have a cap -> one row per date for the next 4 weeks, starts_at in UTC.
// Pure (no fs). tools/seed-events.mjs writes the result into schema.sql and src/data/signup-events.json.
import { zoned } from './hours.js';
import { gameId } from './events.js';

export const TZ = 'America/New_York';
export const WEEKS = 4;

const plus = (date, n) => { const [y, m, d] = date.split('-').map(Number); return new Date(Date.UTC(y, m - 1, d + n)).toISOString().slice(0, 10); };

// Wall clock in `tz` (date YYYY-MM-DD, time HH:MM) -> UTC 'YYYY-MM-DD HH:MM'. Two passes settle the offset around DST changes.
export function localToUtc(date, time, tz = TZ) {
  const [y, m, d] = date.split('-').map(Number), [hh, mm] = time.split(':').map(Number);
  const want = Date.UTC(y, m - 1, d, hh, mm);
  let t = want;
  for (let i = 0; i < 2; i++) {
    const z = zoned(tz, new Date(t)), [zy, zm, zd] = z.date.split('-').map(Number);
    t += want - (Date.UTC(zy, zm - 1, zd) + z.min * 60000);
  }
  return new Date(t).toISOString().slice(0, 16).replace('T', ' ');
}

// `from` is a store-zone YYYY-MM-DD; rows run from that date for 28 days, by date then time. ids are 1..n in that order.
export function seedEvents(weekly, from) {
  const rows = [];
  for (let i = 0; i < WEEKS * 7; i++) {
    const date = plus(from, i), day = new Date(date + 'T00:00:00Z').getUTCDay();
    for (const e of weekly.filter((w) => w.day === day && w.cap !== null && w.cap !== undefined)) rows.push({ date, e });
  }
  rows.sort((a, b) => (a.date + a.e.time).localeCompare(b.date + b.e.time));
  return rows.map(({ date, e }, i) => ({
    id: i + 1, title: e.format, game: gameId(e.game), date, time: e.time, starts_at: localToUtc(date, e.time),
    seats: e.cap, fee_cents: e.fee === null || e.fee === undefined ? null : e.fee * 100,
  }));
}

const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
export function seedSql(rows, from) {
  const vals = rows.map((r) => `  (${r.id}, ${q(r.title)}, ${q(r.game)}, ${q(r.starts_at)}, ${r.seats}, ${r.fee_cents ?? 'NULL'})`).join(',\n');
  return `-- BEGIN seed-events (generated by tools/seed-events.mjs from src/data/events.json; do not edit; from ${from})\n` +
    `INSERT INTO events (id, title, game, starts_at, seats, fee_cents) VALUES\n${vals};\n-- END seed-events`;
}
